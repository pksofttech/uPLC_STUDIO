    /// Export a LadderProgram to IEC 61131-3 Instruction List (IL) standard
    pub fn export_il(prog: &LadderProgram) -> String {
        let mut out = String::new();
        out.push_str("(* ==================================================================== *)\n");
        out.push_str("(* IEC 61131-3 Instruction List (IL) Program                            *)\n");
        out.push_str(&format!("(* Target Hardware: {:<51} *)\n", prog.hardware));
        out.push_str("(* Generated by LaduinoPLC [PksofttecH]                                *)\n");
        out.push_str("(* Compatible with OpenPLC / CODESYS                                    *)\n");
        out.push_str("(* ==================================================================== *)\n\n");

        out.push_str("PROGRAM MainProgram\n");
        out.push_str(&Self::map_io_to_iec_var_table(prog));
        out.push_str("\n\n");

        // Networks / Rungs
        for (idx, rung) in prog.rungs.iter().enumerate() {
            out.push_str(&format!("(* Network {:02}: {} *)\n", idx + 1, rung.comment));
            Self::export_il_rung(&mut out, rung);
            out.push_str("\n");
        }

        out.push_str("END_PROGRAM\n");
        out
    }

    /// Map program I/O and function blocks to standard IEC 61131-3 VAR ... END_VAR table.
    pub fn map_io_to_iec_var_table(prog: &LadderProgram) -> String {
        Self::map_io_to_iec_var_table_with_options(prog, false)
    }

    /// Map program I/O to IEC 61131-3 VAR ... END_VAR table with configurable identifier style.
    pub fn map_io_to_iec_var_table_with_options(prog: &LadderProgram, use_symbol_name: bool) -> String {
        let mut out = String::new();
        out.push_str("VAR\n");

        let entries = prog.map_io_to_iec_var_entries(use_symbol_name);

        let inputs: Vec<_> = entries.iter().filter(|e| e.is_input).collect();
        if !inputs.is_empty() {
            out.push_str("    (* --- Digital Inputs (%IX) --- *)\n");
            for e in inputs {
                out.push_str(&format!("{}\n", e.to_declaration_line()));
            }
            out.push_str("\n");
        }

        let outputs: Vec<_> = entries.iter().filter(|e| !e.is_input).collect();
        if !outputs.is_empty() {
            out.push_str("    (* --- Digital Outputs (%QX) --- *)\n");
            for e in outputs {
                out.push_str(&format!("{}\n", e.to_declaration_line()));
            }
            out.push_str("\n");
        }

        // Declare Function Blocks (Timers, Counters, Registers)
        let mut declared_fbs = HashSet::new();
        let mut fb_block = String::new();
        for rung in &prog.rungs {
            Self::collect_fb_declarations(&rung.elements, &mut declared_fbs, &mut fb_block);
        }
        if !fb_block.is_empty() {
            out.push_str("    (* --- Function Blocks & Internal Registers --- *)\n");
            out.push_str(&fb_block);
        }

        out.push_str("END_VAR");

        // Declare Retentive / Persistent Variables (M64..M95, D96..D127 = %MW96..%MW127)
        let mut persistent_vars = HashSet::new();
        let mut persistent_block = String::new();
        for rung in &prog.rungs {
            for el in &rung.elements {
                for addr in [&el.name, &el.target_reg, &el.fb.in1, &el.fb.in2] {
                    if let Some((decl, comment)) = Self::check_persistent_address(addr) {
                        if persistent_vars.insert(decl.clone()) {
                            persistent_block.push_str(&format!("    {} : {}\n", decl, comment));
                        }
                    }
                }
            }
        }
        if !persistent_block.is_empty() {
            out.push_str("\n\nVAR RETAIN PERSISTENT\n");
            out.push_str("    (* --- Retentive / Persistent Memory (RP2040 Flash) --- *)\n");
            out.push_str(&persistent_block);
            out.push_str("END_VAR");
        }

        out
    }

    /// RETAIN check: `M64..M95` (`%MX8.0..%MX11.7`) and `D96..D127` (`%MW96..%MW127`), matching the
    /// area latched to Flash by the RP2040 firmware (`bit_mem[0x80..0xA0]`, `word_mem[0x80..0xA0]`).
    pub fn check_persistent_address(name: &str) -> Option<(String, &'static str)> {
        let s = name.trim().to_uppercase();
        if s.starts_with("%MX") {
            if let Some((b_str, bit_str)) = s[3..].split_once('.') {
                if let (Ok(byte), Ok(bit)) = (b_str.parse::<usize>(), bit_str.parse::<usize>()) {
                    let idx = byte * 8 + bit;
                    if (64..=95).contains(&idx) {
                        return Some((format!("M{} AT %MX{}.{}", idx, byte, bit), "BOOL := FALSE; (* Retentive Bit Relay M64..M95 *)"));
                    }
                }
            }
        } else if s.starts_with('M') && s.len() > 1 && s[1..].chars().all(|c| c.is_ascii_digit()) {
            if let Ok(idx) = s[1..].parse::<usize>() {
                if (64..=95).contains(&idx) {
                    let byte = idx / 8;
                    let bit = idx % 8;
                    return Some((format!("M{} AT %MX{}.{}", idx, byte, bit), "BOOL := FALSE; (* Retentive Bit Relay M64..M95 *)"));
                }
            }
        } else if s.starts_with("%MW") {
            if let Ok(idx) = s[3..].parse::<usize>() {
                if (96..=127).contains(&idx) {
                    return Some((format!("D{} AT %MW{}", idx, idx), "INT := 0; (* Retentive Word Register D96..D127 *)"));
                }
            }
        } else if (s.starts_with('D') || s.starts_with('V')) && s.len() > 1 && s[1..].chars().all(|c| c.is_ascii_digit()) {
            if let Ok(idx) = s[1..].parse::<usize>() {
                if (96..=127).contains(&idx) {
                    return Some((format!("D{} AT %MW{}", idx, idx), "INT := 0; (* Retentive Word Register D96..D127 *)"));
                }
            }
        }
        None
    }

    pub fn collect_fb_declarations(
        elements: &[LadderElement],
        declared: &mut HashSet<String>,
        out: &mut String,
    ) {
        for el in elements {
            match el.element_type {
                TypeTag::Ton => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : TON; (* Preset: {}ms *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::Tof => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : TOF; (* Preset: {}ms *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::Tp => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : TP; (* Preset: {}ms *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::Ctu => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : CTU; (* Preset: {} *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::Ctd => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : CTD; (* Preset: {} *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::Ctud => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : CTUD; (* Preset: {} *)\n", el.name, el.preset_value));
                    }
                }
                TypeTag::RTrig => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : R_TRIG;\n", el.name));
                    }
                }
                TypeTag::FTrig => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : F_TRIG;\n", el.name));
                    }
                }
                TypeTag::Sr => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : SR;\n", el.name));
                    }
                }
                TypeTag::MbMaster => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!(
                            "    {} : MB_MASTER; (* Slave: {}, Func: {}, Addr: {}, Count: {}, Buffer: {} *)\n",
                            el.name, el.mb_slave_id, el.mb_function, el.preset_value, el.preset_value1, el.target_reg
                        ));
                    }
                }
                TypeTag::Rs => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : RS;\n", el.name));
                    }
                }
                TypeTag::Pid => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!(
                            "    {} : PID; (* Kp={:.2} Ki={:.2} Kd={:.2} OutMax={} *)\n",
                            el.name,
                            el.fb.k[0] as f64 / 100.0,
                            el.fb.k[1] as f64 / 100.0,
                            el.fb.k[2] as f64 / 100.0,
                            el.fb.k[3]
                        ));
                    }
                }
                TypeTag::Scale => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : SCALE;\n", el.name));
                    }
                }
                TypeTag::Limit => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : LIMIT;\n", el.name));
                    }
                }
                TypeTag::UartSend => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : UART_SEND;\n", el.name));
                    }
                }
                TypeTag::UartRecv => {
                    if declared.insert(el.name.clone()) {
                        out.push_str(&format!("    {} : UART_RECV;\n", el.name));
                    }
                }
                TypeTag::Move | TypeTag::Math | TypeTag::Compare => {
                    if declared.insert(el.name.clone())
                        && !el.name.starts_with('X')
                        && !el.name.starts_with('Y')
                        && Self::check_persistent_address(&el.name).is_none()
                    {
                        out.push_str(&format!("    {} : INT := 0; (* Internal Register *)\n", el.name));
                    }
                }
                TypeTag::Branch => {
                    for path in &el.branch_paths {
                        Self::collect_fb_declarations(path, declared, out);
                    }
                }
                _ => {}
            }
        }
    }

    fn export_il_rung(out: &mut String, rung: &Rung) {
        if rung.elements.is_empty() {
            return;
        }

        let mut first = true;
        for el in &rung.elements {
            match el.element_type {
                TypeTag::Contact => {
                    let (cmd_first, cmd_next) = match el.contact_mode {
                        ContactMode::NormallyOpen => ("LD  ", "AND "),
                        ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                        ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                        ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                    };
                    let cmd = if first { cmd_first } else { cmd_next };
                    out.push_str(&format!("    {} {}\n", cmd, el.name));
                    first = false;
                }
                TypeTag::Coil => {
                    let cmd = match el.coil_mode {
                        CoilMode::Normal => "ST  ",
                        CoilMode::Negated => "STN ",
                        CoilMode::SetLatch => "S   ",
                        CoilMode::ResetUnlatch => "R   ",
                        CoilMode::PositiveTransition => "STP ",
                        CoilMode::NegativeTransition => "STF ",
                    };
                    out.push_str(&format!("    {} {}\n", cmd, el.name));
                    first = false;
                }
                TypeTag::Branch => {
                    if first {
                        // Branch at start of rung
                        if let Some(first_path) = el.branch_paths.first() {
                            let mut path_first = true;
                            for sub in first_path {
                                let (cmd_f, cmd_n) = match sub.contact_mode {
                                    ContactMode::NormallyOpen => ("LD  ", "AND "),
                                    ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                                    ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                                    ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                                };
                                let cmd = if path_first { cmd_f } else { cmd_n };
                                out.push_str(&format!("    {} {}\n", cmd, sub.name));
                                path_first = false;
                            }
                        }
                        for path in el.branch_paths.iter().skip(1) {
                            if path.len() == 1 {
                                let sub = &path[0];
                                let cmd = match sub.contact_mode {
                                    ContactMode::NormallyOpen => "OR  ",
                                    ContactMode::NormallyClosed => "ORN ",
                                    ContactMode::PositiveTransition => "ORP ",
                                    ContactMode::NegativeTransition => "ORF ",
                                };
                                out.push_str(&format!("    {} {}\n", cmd, sub.name));
                            } else if !path.is_empty() {
                                let sub0 = &path[0];
                                let cmd0 = match sub0.contact_mode {
                                    ContactMode::NormallyOpen => "OR( ",
                                    ContactMode::NormallyClosed => "ORN(",
                                    ContactMode::PositiveTransition => "ORP(",
                                    ContactMode::NegativeTransition => "ORF(",
                                };
                                out.push_str(&format!("    {} {}\n", cmd0, sub0.name));
                                for sub in path.iter().skip(1) {
                                    let cmd = match sub.contact_mode {
                                        ContactMode::NormallyOpen => "AND ",
                                        ContactMode::NormallyClosed => "ANDN",
                                        ContactMode::PositiveTransition => "ANDP",
                                        ContactMode::NegativeTransition => "ANDF",
                                    };
                                    out.push_str(&format!("    {} {}\n", cmd, sub.name));
                                }
                                out.push_str("    )\n");
                            }
                        }
                        first = false;
                    } else {
                        // Branch in middle of rung
                        out.push_str("    AND(\n");
                        if let Some(first_path) = el.branch_paths.first() {
                            let mut path_first = true;
                            for sub in first_path {
                                let (cmd_f, cmd_n) = match sub.contact_mode {
                                    ContactMode::NormallyOpen => ("LD  ", "AND "),
                                    ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                                    ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                                    ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                                };
                                let cmd = if path_first { cmd_f } else { cmd_n };
                                out.push_str(&format!("        {} {}\n", cmd, sub.name));
                                path_first = false;
                            }
                        }
                        for path in el.branch_paths.iter().skip(1) {
                            if path.len() == 1 {
                                let sub = &path[0];
                                let cmd = match sub.contact_mode {
                                    ContactMode::NormallyOpen => "OR  ",
                                    ContactMode::NormallyClosed => "ORN ",
                                    ContactMode::PositiveTransition => "ORP ",
                                    ContactMode::NegativeTransition => "ORF ",
                                };
                                out.push_str(&format!("        {} {}\n", cmd, sub.name));
                            } else if !path.is_empty() {
                                let sub0 = &path[0];
                                let cmd0 = match sub0.contact_mode {
                                    ContactMode::NormallyOpen => "OR( ",
                                    ContactMode::NormallyClosed => "ORN(",
                                    ContactMode::PositiveTransition => "ORP(",
                                    ContactMode::NegativeTransition => "ORF(",
                                };
                                out.push_str(&format!("        {} {}\n", cmd0, sub0.name));
                                for sub in path.iter().skip(1) {
                                    let cmd = match sub.contact_mode {
                                        ContactMode::NormallyOpen => "AND ",
                                        ContactMode::NormallyClosed => "ANDN",
                                        ContactMode::PositiveTransition => "ANDP",
                                        ContactMode::NegativeTransition => "ANDF",
                                    };
                                    out.push_str(&format!("        {} {}\n", cmd, sub.name));
                                }
                                out.push_str("        )\n");
                            }
                        }
                        out.push_str("    )\n");
                    }
                }
                TypeTag::Ton | TypeTag::Tof | TypeTag::Tp => {
                    out.push_str(&format!("    CAL  {}(IN := TRUE, PT := T#{}ms)\n", el.name, el.preset_value));
                    first = false;
                }
                TypeTag::Ctu | TypeTag::Ctud => {
                    out.push_str(&format!("    CAL  {}(CU := TRUE, PV := {})\n", el.name, el.preset_value));
                    first = false;
                }
                TypeTag::Ctd => {
                    out.push_str(&format!("    CAL  {}(CD := TRUE, PV := {})\n", el.name, el.preset_value));
                    first = false;
                }
                TypeTag::Compare => {
                    let op_iec = match el.compare_op.trim().to_uppercase().as_str() {
                        "==" | "EQ" => "EQ",
                        "!=" | "<>" | "NE" => "NE",
                        ">" | "GT" => "GT",
                        "<" | "LT" => "LT",
                        ">=" | "GE" => "GE",
                        "<=" | "LE" => "LE",
                        _ => "EQ",
                    };
                    out.push_str(&format!("    {}   {} {}\n", op_iec, el.name, el.preset_value));
                    first = false;
                }
                TypeTag::Move => {
                    out.push_str(&format!("    MOVE {} {}\n", el.word_target(), el.preset_value));
                    first = false;
                }
                TypeTag::Math => {
                    let op_name = match el.math_op.as_str() {
                        "-" => "SUB",
                        "*" => "MUL",
                        "/" => "DIV",
                        "%" => "MOD",
                        _ => "ADD",
                    };
                    out.push_str(&format!("    {}  {} {}\n", op_name, el.word_target(), el.preset_value));
                    first = false;
                }
                TypeTag::RTrig => {
                    out.push_str(&format!("    CAL  R_TRIG(CLK := {})\n", el.name));
                    first = false;
                }
                TypeTag::FTrig => {
                    out.push_str(&format!("    CAL  F_TRIG(CLK := {})\n", el.name));
                    first = false;
                }
                TypeTag::MasterRelay => {
                    out.push_str("    MC\n");
                    first = false;
                }
                TypeTag::MbMaster => {
                    out.push_str(&format!(
                        "    CAL  {}(SLAVE := {}, FUNC := {}, ADDR := {}, COUNT := {}, BUFFER := {})\n",
                        el.name, el.mb_slave_id, el.mb_function, el.preset_value, el.preset_value1, el.target_reg
                    ));
                    first = false;
                }
                TypeTag::Sr => {
                    let r_target = if !el.target_reg.is_empty() { &el.target_reg } else { "FALSE" };
                    out.push_str(&format!("    CAL  {}(S1 := TRUE, R := {})\n", el.name, r_target));
                    first = false;
                }
                TypeTag::Rs => {
                    let r_target = if !el.target_reg.is_empty() { &el.target_reg } else { "FALSE" };
                    out.push_str(&format!("    CAL  {}(S := TRUE, R1 := {})\n", el.name, r_target));
                    first = false;
                }
                TypeTag::Jump => {
                    out.push_str(&format!("    JMPC {}\n", el.name));
                    first = false;
                }
                TypeTag::Label => {
                    out.push_str(&format!("{}:\n", el.name));
                    first = false;
                }
                TypeTag::Wire => {
                    out.push_str("    (* WIRE *)\n");
                }
                TypeTag::OpenCircuit => {
                    out.push_str("    (* OPEN *)\n");
                }
                TypeTag::Adc
                | TypeTag::Bitwise
                | TypeTag::Scale
                | TypeTag::Limit
                | TypeTag::Pid
                | TypeTag::ShiftRegisters
                | TypeTag::ShiftRegInbit
                | TypeTag::ShiftRegReset
                | TypeTag::ShiftLeft
                | TypeTag::ShiftRight
                | TypeTag::ShiftVariable
                | TypeTag::UartSend
                | TypeTag::UartRecv => {
                    out.push_str(&Self::export_fb_line(el));
                    out.push('\n');
                    first = false;
                }
                _ => {}
            }
        }
    }

    fn or_zero(s: &str) -> &str {
        if s.trim().is_empty() {
            "0"
        } else {
            s.trim()
        }
    }

    /// IL text (one line, 4-space indent, no newline) of a feature-level-2 function block
    pub fn export_fb_line(el: &LadderElement) -> String {
        let fb = &el.fb;
        let z = Self::or_zero;
        match el.element_type {
            TypeTag::Adc => format!("    ADC   {} {}", z(&el.name), z(&el.target_reg)),
            TypeTag::Bitwise => {
                let mnem = match crate::simulation::bitwise_opcode(&el.math_op) {
                    uplc_vm::OP_WOR => "WOR ",
                    uplc_vm::OP_WXOR => "WXOR",
                    uplc_vm::OP_WNOT => "WNOT",
                    uplc_vm::OP_SHL => "SHL ",
                    uplc_vm::OP_SHR => "SHR ",
                    _ => "WAND",
                };
                if mnem == "WNOT" {
                    format!("    WNOT  {} {}", z(&el.target_reg), z(&fb.in1))
                } else {
                    format!("    {}  {} {} {}", mnem, z(&el.target_reg), z(&fb.in1), z(&fb.in2))
                }
            }
            TypeTag::Scale => format!(
                "    CAL  {}(IN := {}, OUT => {}, IN_MIN := {}, IN_MAX := {}, OUT_MIN := {}, OUT_MAX := {})",
                el.name, z(&fb.in1), z(&el.target_reg), fb.k[0], fb.k[1], fb.k[2], fb.k[3]
            ),
            TypeTag::Limit => format!(
                "    CAL  {}(IN := {}, OUT => {}, MN := {}, MX := {})",
                el.name, z(&fb.in1), z(&el.target_reg), fb.k[0], fb.k[1]
            ),
            TypeTag::Pid => format!(
                "    CAL  {}(PV := {}, SP := {}, CV => {}, KP := {}, KI := {}, KD := {}, OUTMAX := {})",
                el.name, z(&fb.in1), z(&fb.in2), z(&el.target_reg), fb.k[0], fb.k[1], fb.k[2], fb.k[3]
            ),
            TypeTag::ShiftRegisters => format!("    SHIFT_REG {} {} {}", z(&el.name), el.preset_value, z(&fb.in1)),
            TypeTag::ShiftRegInbit => format!("    SHIFT_BIT {} {}", z(&el.name), z(&fb.in1)),
            TypeTag::ShiftRegReset => format!("    SHIFT_RST {}", z(&el.name)),
            TypeTag::ShiftLeft => format!("    SHIFT_L {} {}", z(&el.name), el.preset_value),
            TypeTag::ShiftRight => format!("    SHIFT_R {} {}", z(&el.name), el.preset_value),
            TypeTag::ShiftVariable => format!("    SHIFT_VAR {} {}", z(&el.name), z(&fb.in1)),
            TypeTag::UartSend => format!("    UART_SEND {}(IN := {}, MODE := {})", el.name, z(&fb.in1), fb.mode),
            TypeTag::UartRecv => format!("    UART_RECV {}(OUT => {})", el.name, z(&el.target_reg)),
            _ => String::new(),
        }
    }

    /// Parse the `NAME(K := V, K => V, ...)` parameter list of a `CAL` line into an
    /// uppercase-key map
    fn parse_cal_params(rest: &str) -> HashMap<String, String> {
        let mut map = HashMap::new();
        let inner = match (rest.find('('), rest.rfind(')')) {
            (Some(a), Some(b)) if b > a => &rest[a + 1..b],
            (Some(a), _) => &rest[a + 1..],
            _ => return map,
        };
        for part in inner.split(',') {
            let (k, v) = if let Some((k, v)) = part.split_once(":=") {
                (k, v)
            } else if let Some((k, v)) = part.split_once("=>") {
                (k, v)
            } else {
                continue;
            };
            map.insert(k.trim().to_ascii_uppercase(), v.trim().trim_end_matches(';').trim().to_string());
        }
        map
    }

    fn param_i32(params: &HashMap<String, String>, keys: &[&str], default: i32) -> i32 {
        keys.iter()
            .find_map(|k| params.get(*k))
            .and_then(|v| parse_int_literal(v))
            .map(|v| v.clamp(i32::MIN as i64, i32::MAX as i64) as i32)
            .unwrap_or(default)
    }

    fn param_str(params: &HashMap<String, String>, keys: &[&str]) -> String {
        keys.iter().find_map(|k| params.get(*k)).cloned().unwrap_or_default()
    }

    /// Build a PID / SCALE / LIMIT / UART element from a `CAL`-style parameter list
    fn build_param_fb(id: u64, ty: TypeTag, name: &str, rest: &str) -> LadderElement {
        let p = Self::parse_cal_params(rest);
        let mut el = LadderElement {
            id,
            element_type: ty,
            name: name.to_string(),
            symbol: name.to_string(),
            target_reg: String::new(),
            ..Default::default()
        };
        match ty {
            TypeTag::Pid => {
                el.fb = FbParams {
                    in1: Self::param_str(&p, &["PV"]),
                    in2: Self::param_str(&p, &["SP"]),
                    k: [
                        Self::param_i32(&p, &["KP"], 100),
                        Self::param_i32(&p, &["KI"], 0),
                        Self::param_i32(&p, &["KD"], 0),
                        Self::param_i32(&p, &["OUTMAX", "OUT_MAX", "MAX"], 1000),
                    ],
                    mode: 0,
                };
                el.target_reg = Self::param_str(&p, &["CV", "OUT"]);
            }
            TypeTag::Scale => {
                el.fb = FbParams {
                    in1: Self::param_str(&p, &["IN"]),
                    in2: String::new(),
                    k: [
                        Self::param_i32(&p, &["IN_MIN"], 0),
                        Self::param_i32(&p, &["IN_MAX"], 4095),
                        Self::param_i32(&p, &["OUT_MIN"], 0),
                        Self::param_i32(&p, &["OUT_MAX"], 1000),
                    ],
                    mode: 0,
                };
                el.target_reg = Self::param_str(&p, &["OUT"]);
            }
            TypeTag::Limit => {
                el.fb = FbParams {
                    in1: Self::param_str(&p, &["IN"]),
                    in2: String::new(),
                    k: [Self::param_i32(&p, &["MN", "MIN"], 0), Self::param_i32(&p, &["MX", "MAX"], 0), 0, 0],
                    mode: 0,
                };
                el.target_reg = Self::param_str(&p, &["OUT"]);
            }
            TypeTag::UartSend => {
                el.fb.in1 = Self::param_str(&p, &["IN"]);
                el.fb.mode = Self::param_i32(&p, &["MODE"], 0).clamp(0, 255) as u8;
            }
            TypeTag::UartRecv => {
                el.target_reg = Self::param_str(&p, &["OUT"]);
            }
            _ => {}
        }
        el
    }

    /// Parse IEC 61131-3 Instruction List (IL) string
    pub fn parse_iec_il(content: &str) -> Result<LadderProgram, String> {
        let mut hardware = "Arduino UNO R3".to_string();
        let mut io_mappings = Vec::new();
        let mut rungs = Vec::new();
        let mut next_id = 1000u64;
        let mut fb_presets: HashMap<String, (TypeTag, i32)> = HashMap::new();
        let mut var_symbols: HashMap<String, (String, String)> = HashMap::new();

        let lines: Vec<&str> = content.lines().collect();
        let mut i = 0;
        let mut in_var_section = false;
        let mut current_rung_comment = String::new();
        let mut current_rung_elements: Vec<LadderElement> = Vec::new();

        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        enum ParenKind {
            Or,
            And,
        }

        struct ParenFrame {
            kind: ParenKind,
            elements: Vec<LadderElement>,
        }

        let mut paren_stack: Vec<ParenFrame> = Vec::new();

        while i < lines.len() {
            let raw_line = lines[i];
            let line = raw_line.trim();

            if line.is_empty() {
                i += 1;
                continue;
            }

            // Extract hardware in comments
            if line.contains("Target Hardware:") {
                if let Some(pos) = line.find("Target Hardware:") {
                    let after = &line[pos + "Target Hardware:".len()..];
                    let hw = after.trim().trim_end_matches("*)").trim();
                    if !hw.is_empty() {
                        hardware = hw.to_string();
                    }
                }
            } else if line.contains("HARDWARE:") {
                if let Some(pos) = line.find("HARDWARE:") {
                    let after = &line[pos + "HARDWARE:".len()..];
                    let hw = after.trim().trim_end_matches("*)").trim();
                    if !hw.is_empty() {
                        hardware = hw.to_string();
                    }
                }
            }

            // Section markers
            if line.starts_with("VAR") || line == "VAR_INPUT" || line == "VAR_OUTPUT" || line == "VAR_GLOBAL" {
                in_var_section = true;
                i += 1;
                continue;
            } else if line == "END_VAR" {
                in_var_section = false;
                i += 1;
                continue;
            } else if line.starts_with("PROGRAM") {
                i += 1;
                continue;
            } else if line == "END_PROGRAM" {
                if !current_rung_elements.is_empty() || !current_rung_comment.is_empty() {
                    let rung_id = rungs.len();
                    rungs.push(Rung {
                        id: rung_id,
                        comment: current_rung_comment.clone(),
                        elements: current_rung_elements.clone(),
                        is_energized: false,
                    });
                    current_rung_elements.clear();
                    current_rung_comment.clear();
                    paren_stack.clear();
                }
                break;
            }

            if in_var_section {
                Self::parse_var_decl(line, &mut io_mappings, &mut fb_presets, &mut var_symbols);
                i += 1;
                continue;
            }

            // Network / Rung header detection
            if (line.starts_with("(*") && (line.contains("Network") || line.contains("Rung") || line.contains("NETWORK") || line.contains("RUNG")))
                || line.starts_with("NETWORK")
                || line.starts_with("Network")
            {
                if !current_rung_elements.is_empty() || !current_rung_comment.is_empty() {
                    let rung_id = rungs.len();
                    rungs.push(Rung {
                        id: rung_id,
                        comment: current_rung_comment.clone(),
                        elements: current_rung_elements.clone(),
                        is_energized: false,
                    });
                    current_rung_elements.clear();
                    current_rung_comment.clear();
                    paren_stack.clear();
                }

                let comment_text = if let Some(colon_pos) = line.find(':') {
                    let after = &line[colon_pos + 1..];
                    after.trim().trim_end_matches("*)").trim().to_string()
                } else {
                    String::new()
                };
                current_rung_comment = comment_text;
                i += 1;
                continue;
            }

            if line.starts_with("(*") && line.ends_with("*)") && !line.contains("WIRE") && !line.contains("OPEN") {
                i += 1;
                continue;
            }

            let clean_line = if let Some(idx) = line.find("(*") {
                line[..idx].trim()
            } else if let Some(idx) = line.find("//") {
                line[..idx].trim()
            } else {
                line
            };

            if clean_line.is_empty() {
                i += 1;
                continue;
            }

            if clean_line == ")" {
                if let Some(frame) = paren_stack.pop() {
                    let child_elements = frame.elements;
                    if !child_elements.is_empty() {
                        let target_elements = if let Some(parent) = paren_stack.last_mut() {
                            &mut parent.elements
                        } else {
                            &mut current_rung_elements
                        };

                        match frame.kind {
                            ParenKind::And => {
                                target_elements.extend(child_elements);
                            }
                            ParenKind::Or => {
                                if let Some(last) = target_elements.last_mut() {
                                    if last.element_type == TypeTag::Branch {
                                        last.branch_paths.push(child_elements);
                                    } else {
                                        let prev = target_elements.pop().unwrap();
                                        next_id += 1;
                                        target_elements.push(LadderElement::new_branch(
                                            next_id,
                                            vec![vec![prev], child_elements],
                                        ));
                                    }
                                } else {
                                    next_id += 1;
                                    target_elements.push(LadderElement::new_branch(
                                        next_id,
                                        vec![child_elements],
                                    ));
                                }
                            }
                        }
                    }
                }
                i += 1;
                continue;
            }

            if clean_line.starts_with("OR(") {
                let rest = clean_line.strip_prefix("OR(").unwrap_or("").trim();
                let mut frame_elements = Vec::new();
                if !rest.is_empty() && rest != ")" {
                    if let Some(el) = Self::parse_il_instruction(rest, &mut next_id, &fb_presets) {
                        frame_elements.push(el);
                    }
                }
                paren_stack.push(ParenFrame {
                    kind: ParenKind::Or,
                    elements: frame_elements,
                });
                i += 1;
                continue;
            }

            if clean_line.starts_with("AND(") {
                let rest = clean_line.strip_prefix("AND(").unwrap_or("").trim();
                let mut frame_elements = Vec::new();
                if !rest.is_empty() && rest != ")" {
                    if let Some(el) = Self::parse_il_instruction(rest, &mut next_id, &fb_presets) {
                        frame_elements.push(el);
                    }
                }
                paren_stack.push(ParenFrame {
                    kind: ParenKind::And,
                    elements: frame_elements,
                });
                i += 1;
                continue;
            }

            if let Some(elem) = Self::parse_il_instruction(clean_line, &mut next_id, &fb_presets) {
                let target_elements = if let Some(top) = paren_stack.last_mut() {
                    &mut top.elements
                } else {
                    &mut current_rung_elements
                };

                let is_or = clean_line.starts_with("OR ") || clean_line.starts_with("ORN ")
                    || clean_line.starts_with("OR\t") || clean_line.starts_with("ORN\t");
                if is_or {
                    if let Some(last) = target_elements.last_mut() {
                        if last.element_type == TypeTag::Branch {
                            last.branch_paths.push(vec![elem]);
                        } else {
                            let prev = target_elements.pop().unwrap();
                            next_id += 1;
                            target_elements.push(LadderElement::new_branch(
                                next_id,
                                vec![vec![prev], vec![elem]],
                            ));
                        }
                    } else {
                        next_id += 1;
                        target_elements.push(LadderElement::new_branch(next_id, vec![vec![elem]]));
                    }
                } else {
                    target_elements.push(elem);
                }
            }

            i += 1;
        }

        if !current_rung_elements.is_empty() || !current_rung_comment.is_empty() {
            let rung_id = rungs.len();
            rungs.push(Rung {
                id: rung_id,
                comment: current_rung_comment,
                elements: current_rung_elements,
                is_energized: false,
            });
        }

        if rungs.is_empty() {
            rungs.push(Rung::new(0));
        }

        if io_mappings.is_empty() {
            io_mappings = LadderProgram::default_arduino_io();
        }

        // Also populate var_symbols from io_mappings for any fallback IO entries
        for (idx, io) in io_mappings.iter().enumerate() {
            let iec = io.iec_address(idx);
            var_symbols
                .entry(iec.to_uppercase())
                .or_insert_with(|| (io.symbol.clone(), io.description.clone()));
            var_symbols
                .entry(io.plc_address.to_uppercase())
                .or_insert_with(|| (io.symbol.clone(), io.description.clone()));
        }

        for rung in &mut rungs {
            Self::enrich_elements_with_symbols(&mut rung.elements, &var_symbols);
        }

        Ok(LadderProgram {
            title: "Ladder Program (IEC 61131-3 IL) [PksofttecH]".to_string(),
            hardware,
            rungs,
            io_mappings,
            next_element_id: next_id + 1,
        })
    }

    fn enrich_elements_with_symbols(
        elements: &mut [LadderElement],
        var_symbols: &HashMap<String, (String, String)>,
    ) {
        for el in elements {
            if el.element_type == TypeTag::Branch {
                for path in &mut el.branch_paths {
                    Self::enrich_elements_with_symbols(path, var_symbols);
                }
            } else if let Some((sym, desc)) = var_symbols.get(&el.name.to_uppercase()) {
                if !sym.is_empty() && (el.symbol.is_empty() || el.symbol.eq_ignore_ascii_case(&el.name)) {
                    el.symbol = sym.clone();
                }
                if !desc.is_empty() && el.comment.is_empty() {
                    el.comment = desc.clone();
                }
            }
        }
    }

    fn strip_member_suffix(name: &str) -> &str {
        if name.starts_with('%') {
            name
        } else {
            name.split('.').next().unwrap_or(name)
        }
    }

    fn parse_il_instruction(
        line: &str,
        next_id: &mut u64,
        fb_presets: &HashMap<String, (TypeTag, i32)>,
    ) -> Option<LadderElement> {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.is_empty() {
            return None;
        }

        *next_id += 1;
        let id = *next_id;
        let op = parts[0];

        match op {
            "LD" | "AND" | "OR" => {
                let name = parts.get(1).unwrap_or(&"%IX0.0").trim_matches(';');
                let clean_name = Self::strip_member_suffix(name);
                Some(LadderElement::new_contact(id, clean_name, clean_name, ContactMode::NormallyOpen))
            }
            "LDN" | "ANDN" | "ORN" => {
                let name = parts.get(1).unwrap_or(&"%IX0.0").trim_matches(';');
                let clean_name = Self::strip_member_suffix(name);
                Some(LadderElement::new_contact(id, clean_name, clean_name, ContactMode::NormallyClosed))
            }
            "LDP" | "ANDP" | "ORP" => {
                let name = parts.get(1).unwrap_or(&"%IX0.0").trim_matches(';');
                let clean_name = Self::strip_member_suffix(name);
                Some(LadderElement::new_contact(id, clean_name, clean_name, ContactMode::PositiveTransition))
            }
            "LDF" | "ANDF" | "ORF" => {
                let name = parts.get(1).unwrap_or(&"%IX0.0").trim_matches(';');
                let clean_name = Self::strip_member_suffix(name);
                Some(LadderElement::new_contact(id, clean_name, clean_name, ContactMode::NegativeTransition))
            }
            "ST" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                if name.ends_with(".IN") || name.ends_with(".CU") || name.ends_with(".CD") {
                    return None;
                }
                Some(LadderElement::new_coil(id, name, name, CoilMode::Normal))
            }
            "STN" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                Some(LadderElement::new_coil(id, name, name, CoilMode::Negated))
            }
            "STP" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                Some(LadderElement::new_coil(id, name, name, CoilMode::PositiveTransition))
            }
            "STF" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                Some(LadderElement::new_coil(id, name, name, CoilMode::NegativeTransition))
            }
            "S" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                Some(LadderElement::new_coil(id, name, name, CoilMode::SetLatch))
            }
            "R" => {
                let name = parts.get(1).unwrap_or(&"%QX0.0").trim_matches(';');
                Some(LadderElement::new_coil(id, name, name, CoilMode::ResetUnlatch))
            }
            "CAL" => {
                let rest = parts[1..].join(" ");
                let paren_idx = rest.find('(');
                let cal_name = if let Some(idx) = paren_idx {
                    rest[..idx].trim()
                } else {
                    rest.trim_matches(';')
                };

                // 1. Declared FB type first (fixes e.g. `TEMP_PID` being mistaken for a timer),
                //    then parameter signatures, then name heuristics (`T*` timer, `C*` counter).
                let declared_ty = fb_presets.get(cal_name).map(|(t, _)| *t);
                let params = Self::parse_cal_params(&rest);
                let param_ty = if params.contains_key("SP") && (params.contains_key("PV") || params.contains_key("CV")) {
                    Some(TypeTag::Pid)
                } else if params.contains_key("IN_MIN") || params.contains_key("OUT_MIN") {
                    Some(TypeTag::Scale)
                } else if params.contains_key("MN") || params.contains_key("MX") {
                    Some(TypeTag::Limit)
                } else {
                    None
                };
                match declared_ty.or(param_ty) {
                    Some(ty @ (TypeTag::Pid | TypeTag::Scale | TypeTag::Limit | TypeTag::UartSend | TypeTag::UartRecv)) => {
                        return Some(Self::build_param_fb(id, ty, cal_name, &rest));
                    }
                    _ => {}
                }
                let is_timer_decl = matches!(declared_ty, Some(TypeTag::Ton | TypeTag::Tof | TypeTag::Tp));
                let is_counter_decl = matches!(declared_ty, Some(TypeTag::Ctu | TypeTag::Ctd | TypeTag::Ctud));

                if is_timer_decl || (declared_ty.is_none() && cal_name.starts_with('T')) {
                    let mut preset = fb_presets.get(cal_name).map(|(_, p)| *p).unwrap_or(1000);
                    let mut timer_type = fb_presets.get(cal_name).map(|(t, _)| *t).unwrap_or(TypeTag::Ton);
                    if rest.contains("(TP)") || rest.contains(" TP") {
                        timer_type = TypeTag::Tp;
                    } else if rest.contains("(TOF)") || rest.contains(" TOF") {
                        timer_type = TypeTag::Tof;
                    }
                    if let Some(idx) = rest.find("PT :=") {
                        let pt_part = &rest[idx + "PT :=".len()..];
                        let pt_val_str = pt_part.split(|c: char| c == ',' || c == ')').next().unwrap_or("").trim();
                        let clean = pt_val_str.trim_start_matches("T#").trim_end_matches("ms").trim_end_matches('s');
                        if let Ok(v) = clean.parse::<i32>() {
                            preset = if pt_val_str.ends_with('s') && !pt_val_str.ends_with("ms") { v * 1000 } else { v };
                        }
                    }
                    let mut el = LadderElement::new_ton(id, cal_name, cal_name, preset);
                    el.element_type = timer_type;
                    return Some(el);
                }

                if is_counter_decl || (declared_ty.is_none() && cal_name.starts_with('C')) {
                    let mut pv = fb_presets.get(cal_name).map(|(_, p)| *p).unwrap_or(10);
                    let mut counter_type = fb_presets.get(cal_name).map(|(t, _)| *t).unwrap_or(TypeTag::Ctu);
                    if rest.contains("(CTUD)") || rest.contains(" CTUD") {
                        counter_type = TypeTag::Ctud;
                    } else if rest.contains("(CTD)") || rest.contains(" CTD") || rest.contains("CD :=") {
                        counter_type = TypeTag::Ctd;
                    }
                    if let Some(idx) = rest.find("PV :=") {
                        let pv_part = &rest[idx + "PV :=".len()..];
                        let pv_val_str = pv_part.split(|c: char| c == ',' || c == ')').next().unwrap_or("").trim();
                        if let Ok(v) = pv_val_str.parse::<i32>() {
                            pv = v;
                        }
                    }
                    let mut el = LadderElement::new_ctu(id, cal_name, cal_name, pv);
                    el.element_type = counter_type;
                    return Some(el);
                }

                if cal_name.contains("R_TRIG") || cal_name.contains("OSR") {
                    return Some(LadderElement {
                        id,
                        element_type: TypeTag::RTrig,
                        name: "R_TRIG".to_string(),
                        symbol: "R_TRIG".to_string(),
                        ..Default::default()
                    });
                }
                if cal_name.contains("F_TRIG") || cal_name.contains("OSF") {
                    return Some(LadderElement {
                        id,
                        element_type: TypeTag::FTrig,
                        name: "F_TRIG".to_string(),
                        symbol: "F_TRIG".to_string(),
                        ..Default::default()
                    });
                }
                if cal_name.contains("SR") || fb_presets.get(cal_name).map(|(t, _)| *t == TypeTag::Sr).unwrap_or(false) {
                    let r_tag = if let Some(idx) = rest.find("R :=") {
                        let r_part = &rest[idx + "R :=".len()..];
                        r_part.split(|c: char| c == ',' || c == ')').next().unwrap_or("").trim().to_string()
                    } else {
                        String::new()
                    };
                    return Some(LadderElement {
                        id,
                        element_type: TypeTag::Sr,
                        name: cal_name.to_string(),
                        symbol: cal_name.to_string(),
                        target_reg: r_tag,
                        ..Default::default()
                    });
                }
                if cal_name.contains("RS") || fb_presets.get(cal_name).map(|(t, _)| *t == TypeTag::Rs).unwrap_or(false) {
                    let r1_tag = if let Some(idx) = rest.find("R1 :=") {
                        let r_part = &rest[idx + "R1 :=".len()..];
                        r_part.split(|c: char| c == ',' || c == ')').next().unwrap_or("").trim().to_string()
                    } else {
                        String::new()
                    };
                    return Some(LadderElement {
                        id,
                        element_type: TypeTag::Rs,
                        name: cal_name.to_string(),
                        symbol: cal_name.to_string(),
                        target_reg: r1_tag,
                        ..Default::default()
                    });
                }

                if cal_name.starts_with("MB")
                    || cal_name.contains("MB_MASTER")
                    || fb_presets
                        .get(cal_name)
                        .map(|(t, _)| *t == TypeTag::MbMaster)
                        .unwrap_or(false)
                {
                    let mut slave = 1u8;
                    let mut func = 3u8;
                    let mut addr = 0i32;
                    let mut count = 1i32;
                    let mut buffer = "D0".to_string();

                    if let Some(idx) = rest.find("SLAVE :=") {
                        let part = &rest[idx + "SLAVE :=".len()..];
                        if let Some(s) = part.split(|c: char| c == ',' || c == ')').next() {
                            if let Ok(v) = s.trim().parse::<u8>() {
                                slave = v;
                            }
                        }
                    }
                    if let Some(idx) = rest.find("FUNC :=") {
                        let part = &rest[idx + "FUNC :=".len()..];
                        if let Some(s) = part.split(|c: char| c == ',' || c == ')').next() {
                            if let Ok(v) = s.trim().parse::<u8>() {
                                func = v;
                            }
                        }
                    }
                    if let Some(idx) = rest.find("ADDR :=") {
                        let part = &rest[idx + "ADDR :=".len()..];
                        if let Some(s) = part.split(|c: char| c == ',' || c == ')').next() {
                            if let Ok(v) = s.trim().parse::<i32>() {
                                addr = v;
                            }
                        }
                    }
                    if let Some(idx) = rest.find("COUNT :=") {
                        let part = &rest[idx + "COUNT :=".len()..];
                        if let Some(s) = part.split(|c: char| c == ',' || c == ')').next() {
                            if let Ok(v) = s.trim().parse::<i32>() {
                                count = v;
                            }
                        }
                    }
                    if let Some(idx) = rest.find("BUFFER :=") {
                        let part = &rest[idx + "BUFFER :=".len()..];
                        if let Some(s) = part.split(|c: char| c == ',' || c == ')').next() {
                            buffer = s.trim().to_string();
                        }
                    }

                    return Some(LadderElement {
                        id,
                        element_type: TypeTag::MbMaster,
                        name: cal_name.to_string(),
                        symbol: cal_name.to_string(),
                        preset_value: addr,
                        preset_value1: count,
                        target_reg: buffer,
                        mb_slave_id: slave,
                        mb_function: func,
                        ..Default::default()
                    });
                }

                None
            }
            "MOVE" => {
                let name = parts.get(1).unwrap_or(&"%MW0").trim_matches(';');
                let val: i32 = parts.get(2).and_then(|v| v.trim_matches(';').parse().ok()).unwrap_or(0);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Move,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: name.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "FCP" => {
                let name = parts.get(1).unwrap_or(&"%MW0").trim_matches(';');
                let op = parts.get(2).unwrap_or(&"==");
                let val: i32 = parts.get(3).and_then(|v| v.trim_matches(';').parse().ok()).unwrap_or(0);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Compare,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    compare_op: op.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "EQ" | "NE" | "GT" | "LT" | "GE" | "LE" => {
                let cmp_op = match op {
                    "EQ" => "==",
                    "NE" => "!=",
                    "GT" => ">",
                    "LT" => "<",
                    "GE" => ">=",
                    "LE" => "<=",
                    _ => "==",
                };
                let (name, val) = if parts.len() >= 3 {
                    (parts[1].trim_matches(';'), parts[2].trim_matches(';').parse().unwrap_or(0))
                } else {
                    ("%MW0", parts.get(1).and_then(|v| v.trim_matches(';').parse().ok()).unwrap_or(0))
                };
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Compare,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    compare_op: cmp_op.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "ADD" | "SUB" | "MUL" | "DIV" | "MOD" => {
                let name = parts.get(1).unwrap_or(&"%MW0").trim_matches(';');
                let val: i32 = parts.get(2).and_then(|v| v.trim_matches(';').parse().ok()).unwrap_or(1);
                let math_op = match op {
                    "ADD" => "+",
                    "SUB" => "-",
                    "MUL" => "*",
                    "DIV" => "/",
                    "MOD" => "%",
                    _ => "+",
                };
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Math,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: name.to_string(),
                    math_op: math_op.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "MC" | "MASTER_RELAY" => Some(LadderElement {
                id,
                element_type: TypeTag::MasterRelay,
                name: "Master_Relay".to_string(),
                symbol: "MR".to_string(),
                ..Default::default()
            }),
            "SR" => {
                let name = parts.get(1).unwrap_or(&"SR1").trim_matches(';');
                let r_reg = parts.get(2).unwrap_or(&"").trim_matches(';');
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Sr,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: r_reg.to_string(),
                    ..Default::default()
                })
            }
            "RS" => {
                let name = parts.get(1).unwrap_or(&"RS1").trim_matches(';');
                let r1_reg = parts.get(2).unwrap_or(&"").trim_matches(';');
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Rs,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: r1_reg.to_string(),
                    ..Default::default()
                })
            }
            "TON" | "TOF" | "TP" => {
                let name = parts.get(1).unwrap_or(&"T0").trim_matches(|c| c == ',' || c == ';');
                let preset_raw = parts.get(2).unwrap_or(&"1000").trim_matches(';');
                let preset_clean = preset_raw
                    .trim_start_matches(|c: char| c == 'K' || c == 'k' || c == '#')
                    .trim_start_matches("T#")
                    .trim_end_matches("ms")
                    .trim_end_matches('s');
                let preset = preset_clean
                    .parse::<i32>()
                    .unwrap_or_else(|_| fb_presets.get(name).map(|(_, p)| *p).unwrap_or(1000));
                let mut el = LadderElement::new_ton(id, name, name, preset);
                el.element_type = match op {
                    "TOF" => TypeTag::Tof,
                    "TP" => TypeTag::Tp,
                    _ => TypeTag::Ton,
                };
                Some(el)
            }
            "CTU" | "CTD" | "CTUD" => {
                let name = parts.get(1).unwrap_or(&"C0").trim_matches(|c| c == ',' || c == ';');
                let pv_raw = parts.get(2).unwrap_or(&"10").trim_matches(';');
                let pv_clean = pv_raw.trim_start_matches(|c: char| c == 'K' || c == 'k' || c == '#');
                let pv = pv_clean
                    .parse::<i32>()
                    .unwrap_or_else(|_| fb_presets.get(name).map(|(_, p)| *p).unwrap_or(10));
                let mut el = LadderElement::new_ctu(id, name, name, pv);
                el.element_type = match op {
                    "CTD" => TypeTag::Ctd,
                    "CTUD" => TypeTag::Ctud,
                    _ => TypeTag::Ctu,
                };
                Some(el)
            }
            "JMP" | "JMPC" | "JMPCN" => {
                let name = parts.get(1).unwrap_or(&"LBL1").trim_matches(';');
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Jump,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    ..Default::default()
                })
            }
            "LBL" | "LABEL" => {
                let name = parts.get(1).unwrap_or(&"LBL1").trim_matches(';');
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Label,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    ..Default::default()
                })
            }
            "WAND" | "WOR" | "WXOR" | "WNOT" | "SHL" | "SHR" => {
                let arg = |i: usize| parts.get(i).map(|v| v.trim_matches(|c| c == ',' || c == ';').to_string()).unwrap_or_default();
                let math_op = match op {
                    "WOR" => "OR",
                    "WXOR" => "XOR",
                    "WNOT" => "NOT",
                    "SHL" => "SHL",
                    "SHR" => "SHR",
                    _ => "AND",
                };
                let out_reg = arg(1);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Bitwise,
                    name: op.to_string(),
                    symbol: op.to_string(),
                    math_op: math_op.to_string(),
                    target_reg: out_reg,
                    fb: FbParams {
                        in1: arg(2),
                        in2: if op == "WNOT" { String::new() } else { arg(3) },
                        ..Default::default()
                    },
                    ..Default::default()
                })
            }
            "ADC" => {
                let arg = |i: usize| parts.get(i).map(|v| v.trim_matches(|c| c == ',' || c == ';').to_string()).unwrap_or_default();
                let ch = arg(1);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Adc,
                    name: if ch.is_empty() { "%IW0".to_string() } else { ch.clone() },
                    symbol: "ADC".to_string(),
                    target_reg: arg(2),
                    ..Default::default()
                })
            }
            "SHIFT_REG" | "SHIFT_BIT" | "SHIFT_RST" | "SHIFT_L" | "SHIFT_R" | "SHIFT_VAR" => {
                let arg = |i: usize| parts.get(i).map(|v| v.trim_matches(|c| c == ',' || c == ';').to_string()).unwrap_or_default();
                let (ty, preset, in1) = match op {
                    "SHIFT_REG" => (
                        TypeTag::ShiftRegisters,
                        parse_int_literal(&arg(2)).unwrap_or(1) as i32,
                        arg(3),
                    ),
                    "SHIFT_BIT" => (TypeTag::ShiftRegInbit, 0, arg(2)),
                    "SHIFT_RST" => (TypeTag::ShiftRegReset, 0, String::new()),
                    "SHIFT_L" => (TypeTag::ShiftLeft, parse_int_literal(&arg(2)).unwrap_or(1) as i32, String::new()),
                    "SHIFT_R" => (TypeTag::ShiftRight, parse_int_literal(&arg(2)).unwrap_or(1) as i32, String::new()),
                    _ => (TypeTag::ShiftVariable, 0, arg(2)),
                };
                let word = arg(1);
                Some(LadderElement {
                    id,
                    element_type: ty,
                    name: word.clone(),
                    symbol: op.to_string(),
                    target_reg: String::new(),
                    preset_value: preset,
                    fb: FbParams { in1, ..Default::default() },
                    ..Default::default()
                })
            }
            "UART_SEND" | "UART_RECV" => {
                let rest = parts[1..].join(" ");
                let name = rest.split('(').next().unwrap_or("").trim().trim_matches(';');
                let ty = if op == "UART_SEND" { TypeTag::UartSend } else { TypeTag::UartRecv };
                let default_name = if op == "UART_SEND" { "UART_TX" } else { "UART_RX" };
                let name = if name.is_empty() { default_name } else { name };
                Some(Self::build_param_fb(id, ty, name, &rest))
            }
            "SHORT" | "WIRE" => Some(LadderElement::new_wire(id)),
            "OPEN" => Some(LadderElement::new_open(id)),
            _ if op.ends_with(':') => {
                let lbl = op.trim_end_matches(':');
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Label,
                    name: lbl.to_string(),
                    symbol: lbl.to_string(),
                    ..Default::default()
                })
            }
            _ => None,
        }
    }

    fn parse_var_decl(
        line: &str,
        io_mappings: &mut Vec<IOPortMapping>,
        fb_presets: &mut HashMap<String, (TypeTag, i32)>,
        var_symbols: &mut HashMap<String, (String, String)>,
    ) {
        let clean = line.trim().trim_end_matches(';').trim();
        if clean.is_empty() {
            return;
        }

        let (decl_part, comment_part) = if let Some(idx) = clean.find("(*") {
            let decl = clean[..idx].trim();
            let c = clean[idx..].trim_start_matches("(*").trim_end_matches("*)").trim();
            (decl, c)
        } else {
            (clean, "")
        };

        let mut pin = String::new();
        let mut symbol = String::new();
        let mut desc = String::new();
        let mut parsed_preset: Option<i32> = None;

        if !comment_part.is_empty() {
            let parts: Vec<&str> = comment_part.split('|').collect();
            for part in parts {
                let p = part.trim();
                if let Some(stripped) = p.strip_prefix("Pin:") {
                    pin = stripped.trim().to_string();
                } else if let Some(stripped) = p.strip_prefix("Symbol:") {
                    symbol = stripped.trim().to_string();
                } else if let Some(stripped) = p.strip_prefix("Preset:") {
                    let val_str = stripped.trim().trim_end_matches("ms");
                    if let Ok(v) = val_str.parse::<i32>() {
                        parsed_preset = Some(v);
                    }
                } else if !p.is_empty() {
                    desc = p.to_string();
                }
            }
        }

        if decl_part.contains(" AT ") {
            if let Some((name_part, rest)) = decl_part.split_once(" AT ") {
                let name = name_part.trim();
                let addr_and_type = rest.trim();
                let addr = addr_and_type.split(':').next().unwrap_or("").trim();
                let addr_upper = addr.to_uppercase();
                let sym = if !symbol.is_empty() { symbol } else { name.to_string() };
                let hw_pin = if !pin.is_empty() {
                    pin
                } else if name.starts_with('X') || name.starts_with('Y') {
                    name.to_string()
                } else {
                    addr.to_string()
                };
                let description = if !desc.is_empty() { desc } else { format!("Hardware Pin {}", hw_pin) };

                var_symbols.insert(addr_upper.clone(), (sym.clone(), description.clone()));
                var_symbols.insert(name.to_uppercase(), (sym.clone(), description.clone()));

                // Only add physical Input (%I) / Output (%Q) ports to hardware io_mappings (not %M internal markers/words)
                if !addr_upper.starts_with("%M") {
                    let is_input = addr_upper.starts_with("%I") || name.starts_with('X') || name.starts_with('I') || name.starts_with('A');
                    io_mappings.push(IOPortMapping {
                        plc_address: name.to_string(),
                        iec_address: addr.to_string(),
                        symbol: sym,
                        hw_pin,
                        description,
                        is_input,
                    });
                }
            }
        } else if decl_part.contains(':') {
            if let Some((name_part, type_part)) = decl_part.split_once(':') {
                let name = name_part.trim().to_string();
                let ty = type_part.trim().to_uppercase();
                let sym = if !symbol.is_empty() { symbol } else { name.clone() };
                var_symbols.insert(name.to_uppercase(), (sym, desc.clone()));

                // New FB types first (before the SR / RS / TP / CTU prefix checks)
                if ty.starts_with("PID") {
                    fb_presets.insert(name, (TypeTag::Pid, 0));
                } else if ty.starts_with("SCALE") {
                    fb_presets.insert(name, (TypeTag::Scale, 0));
                } else if ty.starts_with("LIMIT") {
                    fb_presets.insert(name, (TypeTag::Limit, 0));
                } else if ty.starts_with("UART_SEND") {
                    fb_presets.insert(name, (TypeTag::UartSend, 0));
                } else if ty.starts_with("UART_RECV") {
                    fb_presets.insert(name, (TypeTag::UartRecv, 0));
                } else if ty.starts_with("TON") {
                    fb_presets.insert(name, (TypeTag::Ton, parsed_preset.unwrap_or(1000)));
                } else if ty.starts_with("TOF") {
                    fb_presets.insert(name, (TypeTag::Tof, parsed_preset.unwrap_or(1000)));
                } else if ty.starts_with("TP") {
                    fb_presets.insert(name, (TypeTag::Tp, parsed_preset.unwrap_or(1000)));
                } else if ty.starts_with("CTUD") {
                    fb_presets.insert(name, (TypeTag::Ctud, parsed_preset.unwrap_or(10)));
                } else if ty.starts_with("CTD") {
                    fb_presets.insert(name, (TypeTag::Ctd, parsed_preset.unwrap_or(10)));
                } else if ty.starts_with("CTU") {
                    fb_presets.insert(name, (TypeTag::Ctu, parsed_preset.unwrap_or(10)));
                } else if ty.starts_with("SR") {
                    fb_presets.insert(name, (TypeTag::Sr, 0));
                } else if ty.starts_with("RS") {
                    fb_presets.insert(name, (TypeTag::Rs, 0));
                } else if ty.starts_with("MB_MASTER") || ty.starts_with("MODBUS") {
                    fb_presets.insert(name, (TypeTag::MbMaster, 0));
                }
            }
        }
    }

