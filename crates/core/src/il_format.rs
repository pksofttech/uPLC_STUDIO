    /// Legacy LDmicro parser for backward compatibility
    pub fn parse_legacy_ld(content: &str) -> Result<LadderProgram, String> {
        let mut hardware = "Arduino UNO R3".to_string();
        let mut io_mappings = Vec::new();
        let mut rungs = Vec::new();
        let mut next_id = 1000u64;

        let lines: Vec<&str> = content.lines().collect();
        let mut i = 0;

        while i < lines.len() {
            let line = lines[i].trim();
            if line.starts_with('#') || line.is_empty() {
                i += 1;
                continue;
            }

            if line == "HARDWARE" {
                i += 1;
                if i < lines.len() {
                    hardware = lines[i].trim().to_string();
                }
            } else if line == "IO LIST" {
                i += 1;
                while i < lines.len() {
                    let io_line = lines[i].trim();
                    if io_line == "END" {
                        break;
                    }
                    if !io_line.is_empty() {
                        if let Some((sym, pin_part)) = io_line.split_once(" at ") {
                            let sym = sym.trim();
                            let pin = pin_part.trim();
                            let is_in = sym.starts_with('X') || sym.starts_with('I') || sym.starts_with('A');
                            io_mappings.push(IOPortMapping {
                                plc_address: sym.to_string(),
                                iec_address: String::new(),
                                symbol: sym.to_string(),
                                hw_pin: pin.to_string(),
                                description: format!("Hardware Pin {}", pin),
                                is_input: is_in,
                            });
                        }
                    }
                    i += 1;
                }
            } else if line == "RUNG" {
                i += 1;
                let mut rung_elements = Vec::new();
                let mut rung_comment = String::new();

                while i < lines.len() {
                    let rung_line = lines[i].trim();
                    if rung_line == "END" {
                        break;
                    }

                    if rung_line.starts_with("PARALLEL") {
                        i += 1;
                        let mut paths = Vec::new();
                        let current_path = Vec::new();

                        while i < lines.len() {
                            let p_line = lines[i].trim();
                            if p_line == "END" {
                                if !current_path.is_empty() {
                                    paths.push(current_path);
                                }
                                break;
                            } else if p_line == "SERIES" {
                                i += 1;
                                let mut series_elements = Vec::new();
                                while i < lines.len() {
                                    let s_line = lines[i].trim();
                                    if s_line == "END" {
                                        break;
                                    }
                                    if let Some(elem) = Self::parse_single_element(s_line, &mut next_id) {
                                        series_elements.push(elem);
                                    }
                                    i += 1;
                                }
                                paths.push(series_elements);
                            } else if let Some(elem) = Self::parse_single_element(p_line, &mut next_id) {
                                paths.push(vec![elem]);
                            }
                            i += 1;
                        }

                        next_id += 1;
                        rung_elements.push(LadderElement::new_branch(next_id, paths));
                    } else if rung_line.starts_with("COMMENT") {
                        let text = rung_line
                            .strip_prefix("COMMENT")
                            .unwrap_or("")
                            .trim()
                            .replace("\\r\\n", "\n");
                        rung_comment = text;
                    } else if let Some(elem) = Self::parse_single_element(rung_line, &mut next_id) {
                        rung_elements.push(elem);
                    }

                    i += 1;
                }

                let rung_id = rungs.len();
                rungs.push(Rung {
                    id: rung_id,
                    comment: rung_comment,
                    elements: rung_elements,
                    is_energized: false,
                });
            }

            i += 1;
        }

        if rungs.is_empty() {
            rungs.push(Rung::new(0));
        }

        if io_mappings.is_empty() {
            io_mappings = LadderProgram::default_arduino_io();
        }

        Ok(LadderProgram {
            title: "Ladder Program By LaduinoPLC [PksofttecH]".to_string(),
            hardware,
            rungs,
            io_mappings,
            next_element_id: next_id + 1,
        })
    }

    fn parse_single_element(line: &str, next_id: &mut u64) -> Option<LadderElement> {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.is_empty() {
            return None;
        }

        *next_id += 1;
        let id = *next_id;

        match parts[0] {
            "CONTACTS" => {
                let name = parts.get(1).unwrap_or(&"X00");
                let is_negated = parts.get(2).map(|&v| v == "1").unwrap_or(false);
                let mode = if is_negated {
                    ContactMode::NormallyClosed
                } else {
                    ContactMode::NormallyOpen
                };
                Some(LadderElement::new_contact(id, *name, *name, mode))
            }
            "COIL" => {
                let name = parts.get(1).unwrap_or(&"Y00");
                let is_negated = parts.get(2).map(|&v| v == "1").unwrap_or(false);
                let is_set = parts.get(3).map(|&v| v == "1").unwrap_or(false);
                let is_reset = parts.get(4).map(|&v| v == "1").unwrap_or(false);
                let mode = if is_set {
                    CoilMode::SetLatch
                } else if is_reset {
                    CoilMode::ResetUnlatch
                } else if is_negated {
                    CoilMode::Negated
                } else {
                    CoilMode::Normal
                };
                Some(LadderElement::new_coil(id, *name, *name, mode))
            }
            "TON" => {
                let name = parts.get(1).unwrap_or(&"T00");
                let raw_val: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(1000);
                let preset_ms = if raw_val >= 10000 { raw_val / 1000 } else { raw_val };
                Some(LadderElement::new_ton(id, *name, *name, preset_ms))
            }
            "TOF" => {
                let name = parts.get(1).unwrap_or(&"T00");
                let raw_val: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(1000);
                let preset_ms = if raw_val >= 10000 { raw_val / 1000 } else { raw_val };
                let mut el = LadderElement::new_ton(id, *name, *name, preset_ms);
                el.element_type = TypeTag::Tof;
                Some(el)
            }
            "TPC" => {
                let name = parts.get(1).unwrap_or(&"T00");
                let p1: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(500);
                let p2: i32 = parts.get(3).and_then(|v| v.parse().ok()).unwrap_or(500);
                let mut el = LadderElement::new_ton(id, *name, *name, p1);
                el.element_type = TypeTag::Tp;
                el.preset_value1 = p2;
                Some(el)
            }
            "CTU" | "CTC" | "CTD" | "CTUD" => {
                let name = parts.get(1).unwrap_or(&"C00");
                let preset: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(10);
                let mut el = LadderElement::new_ctu(id, *name, *name, preset);
                if parts[0] == "CTD" {
                    el.element_type = TypeTag::Ctd;
                } else if parts[0] == "CTC" || parts[0] == "CTUD" {
                    el.element_type = TypeTag::Ctud;
                }
                Some(el)
            }
            "FCP" => {
                let name = parts.get(1).unwrap_or(&"V00");
                let op = parts.get(2).unwrap_or(&"==");
                let val: i32 = parts.get(3).and_then(|v| v.parse().ok()).unwrap_or(0);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Compare,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    compare_op: op.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "MOVE" => {
                let name = parts.get(1).unwrap_or(&"V00");
                let val: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(0);
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Move,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: name.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "ADD" | "SUB" | "MUL" | "DIV" | "MOD" => {
                let name = parts.get(1).unwrap_or(&"V00");
                let val: i32 = parts.get(2).and_then(|v| v.parse().ok()).unwrap_or(1);
                let op = match parts[0] {
                    "ADD" => "+",
                    "SUB" => "-",
                    "MUL" => "*",
                    "DIV" => "/",
                    "MOD" => "%",
                    _ => "+",
                };
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Math,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    target_reg: name.to_string(),
                    math_op: op.to_string(),
                    preset_value: val,
                    ..Default::default()
                })
            }
            "ADC" => {
                let name = parts.get(1).unwrap_or(&"A0");
                Some(LadderElement {
                    id,
                    element_type: TypeTag::Adc,
                    name: name.to_string(),
                    symbol: name.to_string(),
                    ..Default::default()
                })
            }
            "MASTER_RELAY" => Some(LadderElement {
                id,
                element_type: TypeTag::MasterRelay,
                name: "Master_Relay".to_string(),
                symbol: "MR".to_string(),
                ..Default::default()
            }),
            "OSR" | "R_TRIG" => Some(LadderElement {
                id,
                element_type: TypeTag::RTrig,
                name: parts.get(1).unwrap_or(&"R_TRIG").to_string(),
                symbol: "R_TRIG".to_string(),
                ..Default::default()
            }),
            "OSF" | "F_TRIG" => Some(LadderElement {
                id,
                element_type: TypeTag::FTrig,
                name: parts.get(1).unwrap_or(&"F_TRIG").to_string(),
                symbol: "F_TRIG".to_string(),
                ..Default::default()
            }),
            "UART_SEND" => Some(LadderElement {
                id,
                element_type: TypeTag::UartSend,
                name: parts.get(1).unwrap_or(&"UART_TX").to_string(),
                symbol: "UART_SEND".to_string(),
                ..Default::default()
            }),
            "UART_RECV" => Some(LadderElement {
                id,
                element_type: TypeTag::UartRecv,
                name: parts.get(1).unwrap_or(&"UART_RX").to_string(),
                symbol: "UART_RECV".to_string(),
                ..Default::default()
            }),
            "SHORT" | "WIRE" => Some(LadderElement::new_wire(id)),
            "OPEN" => Some(LadderElement::new_open(id)),
            "COMMENT" => {
                let text = parts[1..].join(" ");
                Some(LadderElement::new_comment(id, text))
            }
            _ => None,
        }
    }

    /// Legacy LDmicro exporter
    pub fn export_legacy_ld(prog: &LadderProgram) -> String {
        let mut out = String::new();
        out.push_str("# LD FORMAT copy Form LDMICRO#\n");
        out.push_str("HARDWARE\n");
        out.push_str(&format!("{}\n", prog.hardware));
        out.push_str("IO LIST\n");
        for io in &prog.io_mappings {
            out.push_str(&format!("{} at {}\n", io.symbol, io.hw_pin));
        }
        out.push_str("END\n");
        out.push_str("PROGRAM\n");

        for rung in &prog.rungs {
            out.push_str("RUNG\n");
            if !rung.comment.is_empty() {
                out.push_str(&format!("\tCOMMENT {}\n", rung.comment.replace('\n', "\\r\\n")));
            }
            for el in &rung.elements {
                Self::export_legacy_element(&mut out, el, 1);
            }
            out.push_str("END\n");
        }

        out
    }

    fn export_legacy_element(out: &mut String, el: &LadderElement, indent: usize) {
        let tabs = "\t".repeat(indent);
        match el.element_type {
            TypeTag::Contact => {
                let neg = if el.contact_mode == ContactMode::NormallyClosed { 1 } else { 0 };
                out.push_str(&format!("{}CONTACTS {} {} 0 0\n", tabs, el.name, neg));
            }
            TypeTag::Coil => {
                let (neg, set, reset) = match el.coil_mode {
                    CoilMode::Normal => (0, 0, 0),
                    CoilMode::Negated => (1, 0, 0),
                    CoilMode::SetLatch => (0, 1, 0),
                    CoilMode::ResetUnlatch => (0, 0, 1),
                    CoilMode::PositiveTransition | CoilMode::NegativeTransition => (0, 0, 0),
                };
                out.push_str(&format!("{}COIL {} {} {} {}\n", tabs, el.name, neg, set, reset));
            }
            TypeTag::Ton => {
                out.push_str(&format!("{}TON {} {}\n", tabs, el.name, el.preset_value));
            }
            TypeTag::Tof => {
                out.push_str(&format!("{}TOF {} {}\n", tabs, el.name, el.preset_value));
            }
            TypeTag::Tp => {
                out.push_str(&format!("{}TP {} {} {}\n", tabs, el.name, el.preset_value, el.preset_value1));
            }
            TypeTag::Ctu => {
                out.push_str(&format!("{}CTU {} {}\n", tabs, el.name, el.preset_value));
            }
            TypeTag::Ctd => {
                out.push_str(&format!("{}CTD {} {}\n", tabs, el.name, el.preset_value));
            }
            TypeTag::Ctud => {
                out.push_str(&format!("{}CTUD {} {}\n", tabs, el.name, el.preset_value));
            }
            TypeTag::Wire => {
                out.push_str(&format!("{}SHORT\n", tabs));
            }
            TypeTag::OpenCircuit => {
                out.push_str(&format!("{}OPEN\n", tabs));
            }
            TypeTag::MasterRelay => {
                out.push_str(&format!("{}MASTER_RELAY\n", tabs));
            }
            TypeTag::Branch => {
                out.push_str(&format!("{}PARALLEL\n", tabs));
                for path in &el.branch_paths {
                    if path.len() > 1 {
                        out.push_str(&format!("{}\tSERIES\n", tabs));
                        for sub in path {
                            Self::export_legacy_element(out, sub, indent + 2);
                        }
                        out.push_str(&format!("{}\tEND\n", tabs));
                    } else if let Some(first) = path.first() {
                        Self::export_legacy_element(out, first, indent + 1);
                    }
                }
                out.push_str(&format!("{}END\n", tabs));
            }
            TypeTag::Comment => {
                out.push_str(&format!("{}COMMENT {}\n", tabs, el.comment.replace('\n', "\\r\\n")));
            }
            _ => {}
        }
    }

    /// Generate IEC 61131-3 IL Code (for bottom panel or live preview)
    pub fn generate_il_code(prog: &LadderProgram, selected_rung: Option<usize>) -> String {
        let mut out = String::new();
        if let Some(sel) = selected_rung {
            if let Some(rung) = prog.rungs.get(sel) {
                out.push_str(&format!("(* Network {:02}: {} *)\n", sel + 1, rung.comment));
                Self::export_il_rung(&mut out, rung);
            } else {
                out.push_str("(* No active network selected *)\n");
            }
        } else {
            for (idx, rung) in prog.rungs.iter().enumerate() {
                out.push_str(&format!("(* Network {:02}: {} *)\n", idx + 1, rung.comment));
                Self::export_il_rung(&mut out, rung);
                out.push_str("\n");
            }
        }
        out
    }

    /// Generate IEC 61131-3 IL Code with live inline Accumulator (ACC) & Process Image annotations
    pub fn generate_il_code_online(prog: &LadderProgram, selected_rung: Option<usize>) -> String {
        let mut out = String::new();
        if let Some(sel) = selected_rung {
            if let Some(rung) = prog.rungs.get(sel) {
                out.push_str(&format!(
                    "(* Network {:02}: {} [Rung Energized={}] *)\n",
                    sel + 1,
                    rung.comment,
                    u8::from(rung.is_energized)
                ));
                Self::export_il_rung_online(&mut out, rung);
            } else {
                out.push_str("(* No active network selected *)\n");
            }
        } else {
            for (idx, rung) in prog.rungs.iter().enumerate() {
                out.push_str(&format!(
                    "(* Network {:02}: {} [Rung Energized={}] *)\n",
                    idx + 1,
                    rung.comment,
                    u8::from(rung.is_energized)
                ));
                Self::export_il_rung_online(&mut out, rung);
                out.push_str("\n");
            }
        }
        out
    }

    fn export_il_rung_online(out: &mut String, rung: &Rung) {
        if rung.elements.is_empty() {
            return;
        }

        let mut first = true;
        for el in &rung.elements {
            let cond_b = u8::from(el.is_done);
            let acc_b = u8::from(el.is_energized);
            match el.element_type {
                TypeTag::Contact => {
                    let (cmd_first, cmd_next) = match el.contact_mode {
                        ContactMode::NormallyOpen => ("LD  ", "AND "),
                        ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                        ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                        ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                    };
                    let cmd = if first { cmd_first } else { cmd_next };
                    let instr = format!("    {} {}", cmd, el.name);
                    out.push_str(&format!(
                        "{:<36} (* Bit={} -> ACC={} *)\n",
                        instr, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Coil => {
                    let cmd = match el.coil_mode {
                        CoilMode::Normal => "ST  ",
                        CoilMode::Negated => "STN ",
                        CoilMode::SetLatch => "S   ",
                        CoilMode::ResetUnlatch => "R   ",
                        CoilMode::PositiveTransition => "STP ",
                        CoilMode::NegativeTransition => "STF ",
                    };
                    let instr = format!("    {} {}", cmd, el.name);
                    out.push_str(&format!(
                        "{:<36} (* Out={} |  ACC={} *)\n",
                        instr, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Branch => {
                    if first {
                        if let Some(first_path) = el.branch_paths.first() {
                            let mut path_first = true;
                            for sub in first_path {
                                let (cmd_f, cmd_n) = match sub.contact_mode {
                                    ContactMode::NormallyOpen => ("LD  ", "AND "),
                                    ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                                    ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                                    ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                                };
                                let cmd = if path_first { cmd_f } else { cmd_n };
                                let instr = format!("    {} {}", cmd, sub.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> ACC={} *)\n",
                                    instr,
                                    u8::from(sub.is_done),
                                    u8::from(sub.is_energized)
                                ));
                                path_first = false;
                            }
                        }
                        for path in el.branch_paths.iter().skip(1) {
                            if path.len() == 1 {
                                let sub = &path[0];
                                let cmd = match sub.contact_mode {
                                    ContactMode::NormallyOpen => "OR  ",
                                    ContactMode::NormallyClosed => "ORN ",
                                    ContactMode::PositiveTransition => "ORP ",
                                    ContactMode::NegativeTransition => "ORF ",
                                };
                                let instr = format!("    {} {}", cmd, sub.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> ACC={} *)\n",
                                    instr,
                                    u8::from(sub.is_done),
                                    acc_b
                                ));
                            } else if !path.is_empty() {
                                let sub0 = &path[0];
                                let cmd0 = match sub0.contact_mode {
                                    ContactMode::NormallyOpen => "OR( ",
                                    ContactMode::NormallyClosed => "ORN(",
                                    ContactMode::PositiveTransition => "ORP(",
                                    ContactMode::NegativeTransition => "ORF(",
                                };
                                let instr0 = format!("    {} {}", cmd0, sub0.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> SubACC={} *)\n",
                                    instr0,
                                    u8::from(sub0.is_done),
                                    u8::from(sub0.is_energized)
                                ));
                                for sub in path.iter().skip(1) {
                                    let cmd = match sub.contact_mode {
                                        ContactMode::NormallyOpen => "AND ",
                                        ContactMode::NormallyClosed => "ANDN",
                                        ContactMode::PositiveTransition => "ANDP",
                                        ContactMode::NegativeTransition => "ANDF",
                                    };
                                    let instr = format!("    {} {}", cmd, sub.name);
                                    out.push_str(&format!(
                                        "{:<36} (* Bit={} -> SubACC={} *)\n",
                                        instr,
                                        u8::from(sub.is_done),
                                        u8::from(sub.is_energized)
                                    ));
                                }
                                out.push_str(&format!(
                                    "{:<36} (* Branch -> ACC={} *)\n",
                                    "    )", acc_b
                                ));
                            }
                        }
                        first = false;
                    } else {
                        out.push_str("    AND(\n");
                        if let Some(first_path) = el.branch_paths.first() {
                            let mut path_first = true;
                            for sub in first_path {
                                let (cmd_f, cmd_n) = match sub.contact_mode {
                                    ContactMode::NormallyOpen => ("LD  ", "AND "),
                                    ContactMode::NormallyClosed => ("LDN ", "ANDN"),
                                    ContactMode::PositiveTransition => ("LDP ", "ANDP"),
                                    ContactMode::NegativeTransition => ("LDF ", "ANDF"),
                                };
                                let cmd = if path_first { cmd_f } else { cmd_n };
                                let instr = format!("        {} {}", cmd, sub.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> SubACC={} *)\n",
                                    instr,
                                    u8::from(sub.is_done),
                                    u8::from(sub.is_energized)
                                ));
                                path_first = false;
                            }
                        }
                        for path in el.branch_paths.iter().skip(1) {
                            if path.len() == 1 {
                                let sub = &path[0];
                                let cmd = match sub.contact_mode {
                                    ContactMode::NormallyOpen => "OR  ",
                                    ContactMode::NormallyClosed => "ORN ",
                                    ContactMode::PositiveTransition => "ORP ",
                                    ContactMode::NegativeTransition => "ORF ",
                                };
                                let instr = format!("        {} {}", cmd, sub.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> SubACC={} *)\n",
                                    instr,
                                    u8::from(sub.is_done),
                                    u8::from(sub.is_energized)
                                ));
                            } else if !path.is_empty() {
                                let sub0 = &path[0];
                                let cmd0 = match sub0.contact_mode {
                                    ContactMode::NormallyOpen => "OR( ",
                                    ContactMode::NormallyClosed => "ORN(",
                                    ContactMode::PositiveTransition => "ORP(",
                                    ContactMode::NegativeTransition => "ORF(",
                                };
                                let instr0 = format!("        {} {}", cmd0, sub0.name);
                                out.push_str(&format!(
                                    "{:<36} (* Bit={} -> SubACC={} *)\n",
                                    instr0,
                                    u8::from(sub0.is_done),
                                    u8::from(sub0.is_energized)
                                ));
                                for sub in path.iter().skip(1) {
                                    let cmd = match sub.contact_mode {
                                        ContactMode::NormallyOpen => "AND ",
                                        ContactMode::NormallyClosed => "ANDN",
                                        ContactMode::PositiveTransition => "ANDP",
                                        ContactMode::NegativeTransition => "ANDF",
                                    };
                                    let instr = format!("        {} {}", cmd, sub.name);
                                    out.push_str(&format!(
                                        "{:<36} (* Bit={} -> SubACC={} *)\n",
                                        instr,
                                        u8::from(sub.is_done),
                                        u8::from(sub.is_energized)
                                    ));
                                }
                                out.push_str("        )\n");
                            }
                        }
                        out.push_str(&format!(
                            "{:<36} (* Branch -> ACC={} *)\n",
                            "    )", acc_b
                        ));
                    }
                }
                TypeTag::Ton | TypeTag::Tof | TypeTag::Tp => {
                    let instr = format!("    CAL  {}(IN := TRUE, PT := T#{}ms)", el.name, el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* ET={}ms/{}ms, Q={} -> ACC={} *)\n",
                        instr, el.current_accum, el.preset_value, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Ctu | TypeTag::Ctud => {
                    let instr = format!("    CAL  {}(CU := TRUE, PV := {})", el.name, el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* CV={}/{}, Q={} -> ACC={} *)\n",
                        instr, el.current_accum, el.preset_value, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Ctd => {
                    let instr = format!("    CAL  {}(CD := TRUE, PV := {})", el.name, el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* CV={}/{}, Q={} -> ACC={} *)\n",
                        instr, el.current_accum, el.preset_value, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Compare => {
                    let op_iec = match el.compare_op.trim().to_uppercase().as_str() {
                        "==" | "EQ" => "EQ",
                        "!=" | "<>" | "NE" => "NE",
                        ">" | "GT" => "GT",
                        "<" | "LT" => "LT",
                        ">=" | "GE" => "GE",
                        "<=" | "LE" => "LE",
                        _ => "EQ",
                    };
                    let instr = format!("    {}   {} {}", op_iec, el.name, el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* Word={}, Cond={} -> ACC={} *)\n",
                        instr, el.current_accum, cond_b, acc_b
                    ));
                    first = false;
                }
                TypeTag::Move => {
                    let instr = format!("    MOVE {} {}", el.word_target(), el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* Word={} | ACC={} *)\n",
                        instr, el.current_accum, acc_b
                    ));
                    first = false;
                }
                TypeTag::Math => {
                    let op_name = match el.math_op.as_str() {
                        "-" => "SUB",
                        "*" => "MUL",
                        "/" => "DIV",
                        "%" => "MOD",
                        _ => "ADD",
                    };
                    let instr = format!("    {}  {} {}", op_name, el.word_target(), el.preset_value);
                    out.push_str(&format!(
                        "{:<36} (* Word={} | ACC={} *)\n",
                        instr, el.current_accum, acc_b
                    ));
                    first = false;
                }
                _ => {
                    Self::export_il_rung(out, &Rung {
                        id: rung.id,
                        comment: String::new(),
                        elements: vec![el.clone()],
                        is_energized: rung.is_energized,
                    });
                    first = false;
                }
            }
        }
    }

